    fn parse_hex(s: &str) -> Vec<u8> {
        fn parse_nibble(c: u8) -> u8 {
            match c {
                b'0'..=b'9' => c-b'0',
                b'a'..=b'f' => c-b'a'+0xa,
                b'A'..=b'F' => c-b'A'+0xa,
                _ => panic!("not a hex digit: '{}'", c as char),
            }
        }
        s.bytes()
            .filter(|b| !b.is_ascii_whitespace())
            .tuples::<(_, _)>()
            .map(|tup| match tup {
                (b'.', c) => c,
                (hi, lo) => parse_nibble(hi) << 4 | parse_nibble(lo),
            })
            .collect()
    }
