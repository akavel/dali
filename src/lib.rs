use enumflags2::{bitflags, BitFlags};

#[bitflags]
#[repr(u32)]
#[derive(Copy, Clone, Debug, PartialEq)]
enum Access {
    Public = 0x1,
    Private = 0x2,
    Protected = 0x4,
    Static = 0x8,
    Final = 0x10,
    Synchronized = 0x20,
    Varargs = 0x80,
    Native = 0x100,
    Interface = 0x200,
    Abstract = 0x400,
    Annotation = 0x2000,
    Enum = 0x4000,
    Constructor = 0x1_0000,
}


